def main() -> int:
    here = Path(__file__).resolve().parent
    ts_path = here / "caelestia_es.ts"
    if not ts_path.exists():
        print(f"ERROR: not found {ts_path}", file=sys.stderr)
        return 1

    tree = ET.parse(ts_path)
    root = tree.getroot()

    total = 0
    translated = 0
    missing: list[str] = []

    for ctx in root.findall("context"):
        for msg in ctx.findall("message"):
            src = msg.find("source")
            tr = msg.find("translation")
            if src is None or tr is None or src.text is None:
                continue
            total += 1
            if src.text in TRANSLATIONS:
                tr.text = TRANSLATIONS[src.text]
                if "type" in tr.attrib:
                    del tr.attrib["type"]
                translated += 1
            else:
                missing.append(src.text)

    # Preserve XML declaration and DOCTYPE manually since ElementTree drops them.
    body = ET.tostring(root, encoding="unicode")
    out = '<?xml version="1.0" encoding="utf-8"?>\n<!DOCTYPE TS>\n' + body
    ts_path.write_text(out, encoding="utf-8")

    print(f"Mensajes totales: {total}")
    print(f"Traducidos: {translated}")
    print(f"Sin traducir: {len(missing)}")
    if missing:
        print("Faltantes (primeros 30):")
        for s in sorted(set(missing))[:30]:
            print(f"  {s!r}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
